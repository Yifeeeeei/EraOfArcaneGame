const assert = require('node:assert/strict');
const {DecisionSession} = require('./decision-session.js');
const s = new DecisionSession();
assert.equal(s.snapshot(1), true);
assert.equal(s.begin('a', 1), true);
assert.equal(s.begin('duplicate', 1), false);
assert.equal(s.result({request_id:'a',ok:false}), 'error');
assert.equal(s.revision,1);
assert.equal(s.begin('retry',1),true);
assert.equal(s.result({request_id:'retry',ok:true}),'success');
assert.equal(s.busy,true,'receipt must not unlock before a new authoritative snapshot');
assert.equal(s.snapshot(2),true);
assert.equal(s.busy,false);
assert.equal(s.begin('second',2),true);
s.snapshot(3);
assert.equal(s.result({request_id:'second',ok:true}),'stale','state can arrive before receipt');
assert.equal(s.begin('third',3),true);
assert.equal(s.result({request_id:'second',ok:false}),'stale');
assert.equal(s.busy,true,'old failure must not unlock new flight');
s.disconnect();
assert.equal(s.begin('replay',3),false,'unknown action is never replayed');
s.snapshot(4);
assert.equal(s.begin('new',3),false,'old drafts cannot target new decision');
assert.equal(s.snapshot(2),false,'ignore old snapshots');
assert.equal(s.revision,4);
console.log('decision-session: duplicate, retry, reordered receipt, continuous window, disconnect passed');
const rejected = new DecisionSession();
rejected.snapshot(10); rejected.begin('partial',10);
assert.equal(rejected.result({request_id:'partial',ok:false,state_advanced:true,revision:11,message:'original error'}),'error_waiting');
assert.equal(rejected.busy,true);
assert.equal(rejected.begin('early-retry',10),false);
rejected.snapshot(11);
assert.equal(rejected.busy,false);
assert.equal(rejected.failureMessage(),'original error');
assert.equal(rejected.begin('stale-draft',10),false);
assert.equal(rejected.begin('next',11),true);
rejected.snapshot(12);
assert.equal(rejected.result({request_id:'next',ok:false,state_advanced:true,revision:12,message:'late error'}),'error_synced');
assert.equal(rejected.failureMessage(),'late error');
rejected.begin('future',12);
assert.equal(rejected.result({request_id:'next',ok:false,state_advanced:true,revision:12,message:'old'}),'stale');
assert.equal(rejected.busy,true);
rejected.snapshot(14);
assert.equal(rejected.result({request_id:'future',ok:false,state_advanced:true,revision:13,message:'superseded'}),'stale');
assert.equal(rejected.failureMessage(),'');
console.log('executed errors: wait for state, preserve original error, stale drafts and receipts rejected');
const preflight = new DecisionSession();
preflight.snapshot(20); preflight.begin('unknown',20);
assert.equal(preflight.result({request_id:'unknown',ok:false,state_advanced:false,revision:20,message:'unknown action'}),'error');
assert.equal(preflight.busy,false);
assert.equal(preflight.snapshot(20),false,'unchanged preflight snapshot must not invalidate the draft');
assert.equal(preflight.failureMessage(),'unknown action');
preflight.begin('stale-version',20);
preflight.result({request_id:'stale-version',ok:false,state_advanced:false,revision:21,message:'stale revision'});
preflight.snapshot(21);
assert.equal(preflight.failureMessage(),'stale revision');
