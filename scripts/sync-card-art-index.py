#!/usr/bin/env python3
"""Compile supported original-art URLs and reviewed focal points, never pixels.

data/card-art-focus.csv is the editable table. focus_x/focus_y are percentages
of the ORIGINAL image (left/top = 0, right/bottom = 100), not object-position.
The browser centers that point where possible, clamping at image edges.
"""
import argparse
import csv
import json
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image-repo", type=Path, default=REPO.parent / "ArcaneImages")
    args = parser.parse_args()
    manifest = json.loads((args.image_repo / "drawings/index.json").read_text(encoding="utf-8"))
    if manifest.get("version") != 1 or not isinstance(manifest.get("images"), dict):
        raise ValueError("unsupported original-art index")
    cards = json.loads((REPO / "data/supported_card_infos.json").read_text(encoding="utf-8"))
    with (REPO / "data/card-art-focus.csv").open(encoding="utf-8", newline="") as file:
        rows = list(csv.DictReader(file))
    focus = {row["number"]: row for row in rows}
    if len(focus) != len(rows):
        raise ValueError("duplicate card in focal-point table")
    images = {}
    points = {}
    for card in cards:
        image = manifest["images"].get(card["number"])
        if not image:
            continue
        path = PurePosixPath(image)
        if path.is_absolute() or path.parts[0] != "drawings" or ".." in path.parts or "\\" in image:
            raise ValueError(f"invalid artwork path for {card['number']}")
        images[card["number"]] = image
        row = focus.get(card["number"])
        if not row or row["artwork"] != image:
            raise ValueError(f"artwork needs focal-point review: {card['number']}")
        point = [float(row["focus_x"]), float(row["focus_y"])]
        if any(not 0 <= value <= 100 for value in point):
            raise ValueError(f"focal point outside image: {card['number']}")
        points[card["number"]] = [int(value) if value.is_integer() else value for value in point]
    data = json.dumps(dict(sorted(images.items())), ensure_ascii=False, indent=2)
    focal_data = ",\n".join(f'  "{number}": {json.dumps(point)}' for number, point in sorted(points.items()))
    target = REPO / "web/assets/card-art-index.js"
    text = "// Generated by scripts/sync-card-art-index.py; URLs and original-image focal percentages.\nwindow.ArcaneArtworkIndex = Object.freeze(" + data + ");\n"
    text += "window.ArcaneArtworkFocusIndex = Object.freeze({\n" + focal_data + "\n});\n"
    target.write_text(text, encoding="utf-8")
    print(f"Artwork URLs and reviewed focal points: {len(images)}/{len(cards)}; no image pixels copied")


if __name__ == "__main__":
    main()
