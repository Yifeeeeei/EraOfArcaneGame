#!/usr/bin/env python3
"""Copy the supported cards' original-art URL map from ArcaneImages, not pixels."""
import argparse
import json
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image-repo", type=Path, default=REPO.parent / "ArcaneImages")
    args = parser.parse_args()
    manifest = json.loads((args.image_repo / "drawings/index.json").read_text(encoding="utf-8"))
    if manifest.get("version") != 1 or not isinstance(manifest.get("images"), dict):
        raise ValueError("unsupported original-art index")
    cards = json.loads((REPO / "data/supported_card_infos.json").read_text(encoding="utf-8"))
    images = {}
    for card in cards:
        image = manifest["images"].get(card["number"])
        if not image:
            continue
        path = PurePosixPath(image)
        if path.is_absolute() or path.parts[0] != "drawings" or ".." in path.parts or "\\" in image:
            raise ValueError(f"invalid artwork path for {card['number']}")
        images[card["number"]] = image
    data = json.dumps(dict(sorted(images.items())), ensure_ascii=False, indent=2)
    target = REPO / "web/assets/card-art-index.js"
    text = "// Generated by scripts/sync-card-art-index.py; artwork URLs only.\nwindow.ArcaneArtworkIndex = Object.freeze(" + data + ");\n"
    target.write_text(text, encoding="utf-8")
    print(f"Artwork URLs: {len(images)}/{len(cards)} supported cards; no image pixels copied")


if __name__ == "__main__":
    main()
