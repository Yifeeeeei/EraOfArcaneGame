// Generate the static browser help index from the released compiled card pool.
// Run from server/: go run ./cmd/generate-keyword-index
package main

import (
	"encoding/json"
	"eraofarcane/cards"
	"eraofarcane/internal/cardhelp"
	"fmt"
	"os"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	if err := cards.LoadCards(); err != nil {
		return err
	}
	raw, err := os.ReadFile("../data/card_keyword_glossary.json")
	if err != nil {
		return err
	}
	var definitions []struct {
		ID   string `json:"id"`
		Name string `json:"name"`
		Text string `json:"text"`
	}
	if err := json.Unmarshal(raw, &definitions); err != nil {
		return err
	}
	known := map[string]bool{}
	for _, d := range definitions {
		if d.ID == "" || d.Name == "" || d.Text == "" || known[d.ID] {
			return fmt.Errorf("invalid or duplicate definition %q", d.ID)
		}
		known[d.ID] = true
	}
	index := map[string][]string{}
	for number, card := range cards.PlayableCardDB {
		refs := cardhelp.References(card)
		for _, id := range refs {
			if !known[id] {
				return fmt.Errorf("card %s references missing definition %s", number, id)
			}
		}
		index[number] = refs // Empty arrays explicitly record reviewed blank cards.
	}
	data, err := json.MarshalIndent(map[string]any{"definitions": definitions, "cards": index}, "", "  ")
	if err != nil {
		return err
	}
	output := append([]byte("// Generated by server/cmd/generate-keyword-index; display help only.\nwindow.ArcaneKeywordIndex = "), data...)
	output = append(output, []byte(";\n")...)
	if err := os.WriteFile("../web/assets/card-keyword-index.js", output, 0644); err != nil {
		return err
	}
	fmt.Printf("Indexed %d supported cards and %d definitions\n", len(index), len(definitions))
	return nil
}
